<#
.SYNOPSIS
Install Shikari as a team server on Windows Server 2022+ (#29).

.DESCRIPTION
Lays out data under %ProgramData%\Shikari (SHIKARI_HOME), builds a virtualenv from the checkout, and
registers a boot-start Scheduled Task that runs uvicorn and restarts on failure — a working "service"
using only built-in Windows, no third-party tools. For a true Windows service, see the NSSM note in
docs/deployment/README.md; the layout here is identical, you just point NSSM at the same wrapper.

Run in an elevated PowerShell from a Shikari checkout:
    .\deploy\windows\install-service.ps1 [-CodeDir 'C:\Program Files\Shikari'] [-Port 32453] [-BindHost 127.0.0.1]

Python 3.11+ must be on PATH (or pass -Python). Single worker only: Shikari keeps session, lab-job and
in-browser-console state in-process.
#>
param(
    [string]$CodeDir = 'C:\Program Files\Shikari',
    [string]$DataDir = (Join-Path $env:ProgramData 'Shikari'),
    [int]$Port = 32453,
    [string]$BindHost = '127.0.0.1',
    [string]$Python = '',
    [string]$TaskName = 'Shikari'
)
$ErrorActionPreference = 'Stop'

if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
        [Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Run this in an elevated PowerShell (Run as administrator).'
}

$src = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
Write-Host "==> Shikari team-server install"
Write-Host "    code: $CodeDir   data: $DataDir   bind: ${BindHost}:$Port"

# --- Python 3.11+ ---------------------------------------------------------------------------------
if (-not $Python) {
    $Python = (Get-Command python3.12, python3.11, python -ErrorAction SilentlyContinue | Select-Object -First 1).Source
}
if (-not $Python) { throw 'Python 3.11+ not found. Install it (or pass -Python) and re-run.' }
$pyv = & $Python -c 'import sys; print("%d.%d" % sys.version_info[:2])'
if ([version]$pyv -lt [version]'3.11') { throw "Need Python 3.11+, found $pyv ($Python)." }
Write-Host "    python: $Python ($pyv)"

# --- code: copy the checkout into CodeDir (minus venv/data/bespoke) -------------------------------
Write-Host "==> installing code to $CodeDir"
New-Item -ItemType Directory -Force -Path $CodeDir | Out-Null
robocopy $src $CodeDir /MIR /XD '.venv' 'data' 'bespoke' '.git' /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" } else { $global:LASTEXITCODE = 0 }

# --- virtualenv + dependencies --------------------------------------------------------------------
Write-Host "==> building virtualenv"
$venvPy = Join-Path $CodeDir '.venv\Scripts\python.exe'
if (-not (Test-Path $venvPy)) { & $Python -m venv (Join-Path $CodeDir '.venv') }
& $venvPy -m pip install --quiet --upgrade pip
& $venvPy -m pip install --quiet -e $CodeDir

# --- data dir + launcher wrapper ------------------------------------------------------------------
Write-Host "==> laying out $DataDir"
New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
$wrapper = Join-Path $DataDir 'run-shikari.cmd'
@"
@echo off
rem Generated by install-service.ps1 (#29). Edit the values here, then restart the Shikari task.
set "SHIKARI_HOME=$DataDir"
set "SHIKARI_HOST=$BindHost"
set "SHIKARI_PORT=$Port"
"$venvPy" -m uvicorn shikari.app:app --host %SHIKARI_HOST% --port %SHIKARI_PORT% --workers 1
"@ | Set-Content -Encoding ASCII $wrapper

# --- boot-start Scheduled Task, restart on failure ------------------------------------------------
Write-Host "==> registering Scheduled Task '$TaskName'"
Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
$action   = New-ScheduledTaskAction -Execute $wrapper -WorkingDirectory $CodeDir
$trigger  = New-ScheduledTaskTrigger -AtStartup
$principal= New-ScheduledTaskPrincipal -UserId 'NT AUTHORITY\LocalService' -LogonType ServiceAccount -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit (New-TimeSpan -Seconds 0)
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings | Out-Null

# LocalService must be able to read the code and write the data.
icacls $CodeDir /grant '*S-1-5-19:(OI)(CI)RX' /T /C /Q | Out-Null
icacls $DataDir /grant '*S-1-5-19:(OI)(CI)M'  /T /C /Q | Out-Null

Write-Host "==> starting"
Start-ScheduledTask -TaskName $TaskName

# --- health check ---------------------------------------------------------------------------------
$ok = $false
foreach ($i in 1..30) {
    try { Invoke-WebRequest "http://127.0.0.1:$Port/health" -UseBasicParsing -TimeoutSec 2 | Out-Null; $ok = $true; break }
    catch { Start-Sleep -Seconds 1 }
}
if ($ok) { Write-Host "    healthy on 127.0.0.1:$Port" }
else { Write-Warning "not healthy yet — check Task Scheduler history and $DataDir" }

Write-Host @"

Shikari is installed as the '$TaskName' Scheduled Task (starts at boot, restarts on failure).
  start/stop:  Start-ScheduledTask -TaskName $TaskName  /  Stop-ScheduledTask -TaskName $TaskName
  config:      edit $wrapper, then restart the task
  data:        $DataDir

Put TLS in front of it (IIS/ARR or another reverse proxy on 443 -> 127.0.0.1:$Port) and open the firewall.
For a true Windows service instead of a task, see the NSSM note in docs/deployment/README.md.
"@
