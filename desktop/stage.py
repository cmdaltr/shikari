#!/usr/bin/env python3
"""
Stage the source tree Briefcase builds the installable desktop app from (desktop/README.md).

    .venv/bin/python desktop/stage.py [--out DIR] [--attack FILE] [--procedures FILE ...]
    cd ~/.cache/shikari/desktop && briefcase package --adhoc-sign   (or: briefcase dev)

Only files git would include are staged (tracked, plus new files that aren't ignored), so
what .gitignore keeps out of the repository (bespoke/, data/shikari.db, generated detections)
never reaches an installer, wherever this runs.

The staged tree:
    shikari/ templates/ static/   the code (shikari.paths.ROOT inside the app)
    seed/                        copied into the user's folder on first run (shikari/desktop_app.py):
                                 git's data/, plus --attack (the ATT&CK bundle, to seed/shikari/data/cache)
                                 and --procedures (MITRESaw's CSV and its .meta.json, to seed/data)
    wheels/                      wheels built here for dependencies published only as source (SDIST_ONLY)
    mingit/                      Windows only: Git for Windows' portable MinGit (MINGIT)
    icons/ LICENSE pyproject.toml
"""

import argparse
import hashlib
import io
import platform
import shutil
import subprocess
import sys
import tomllib
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CODE = ("shikari", "templates", "static")
# In [project].dependencies but not used by the app: test tooling
NOT_BUNDLED = {"playwright", "pytest", "pytest-base-url", "pytest-playwright", "hypothesis", "iniconfig",
               "pluggy"}
# Pure Python but published only as source archives, and Briefcase installs wheels only: staging
# builds their wheels (into wheels/, which the build's pip searches). antlr4 is pinned by
# stix2-patterns; proxy_tools comes with pywebview.
SDIST_ONLY = {"antlr4-python3-runtime", "proxy-tools"}
# Published as wheels only, with no source archive to compile where there's no wheel (Windows ARM64):
# built from the tagged source instead
NO_SDIST = {"evtx": "evtx @ git+https://github.com/omerbenamram/pyevtx-rs@{version}"}
# Windows has no git, and the OSINT repos (sparse checkouts; Azure-Sentinel's tarball is 3.4 GB)
# and detection export need it, so the Windows installer carries MinGit, pinned to these hashes
# (the release's published SHA-256s). Keyed by platform.machine(), which Briefcase builds for.
MINGIT_RELEASE = "https://github.com/git-for-windows/git/releases/download/v2.56.0.windows.4"
MINGIT = {
    "AMD64": ("MinGit-2.56.0.4-64-bit.zip", "e3bf78351fe777fba47ddee5950082f8a98bb0f02604fdc7ba3ee2cb68ffa877"),
    "ARM64": ("MinGit-2.56.0.4-arm64.zip", "70f7649f78088c1db1d2f3571ca46a04d5bef06e4e9d56d8ed7f9829e8c6c4db"),
}


def git_files():
    out = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "-z"], cwd=ROOT,
                         capture_output=True, check=True).stdout
    return [Path(p) for p in out.decode().split("\0") if p]


def requirement_name(spec):
    for sep in "=<>!~;[ ":
        spec = spec.split(sep)[0]
    return spec.strip().lower()


def stage_mingit(out, machine):
    name, sha256 = MINGIT[machine]
    with urllib.request.urlopen(f"{MINGIT_RELEASE}/{name}", timeout=300) as r:
        body = r.read()
    if hashlib.sha256(body).hexdigest() != sha256:
        sys.exit(f"{name} doesn't match its pinned SHA-256: refusing to bundle it")
    zipfile.ZipFile(io.BytesIO(body)).extractall(out / "mingit")
    return name


def pyproject(project, wheels, extra_sources=()):
    deps = [d for d in project["dependencies"] if requirement_name(d) not in NOT_BUNDLED]
    webview = project["optional-dependencies"]["desktop"]

    def toml_list(items, indent="    "):
        return "[\n" + "".join(f'{indent}"{i}",\n' for i in items) + "]"

    return f'''# Generated by desktop/stage.py from the repository's pyproject.toml; edit that, not this.
[project]
name = "shikari"
version = "{project["version"]}"
description = "{project["description"]}"
license = "Elastic-2.0"
license-files = ["LICENSE"]
requires-python = "{project["requires-python"]}"
dependencies = {toml_list(deps)}

[tool.briefcase]
project_name = "Shikari"
bundle = "com.cmdaltr"
url = "https://github.com/cmdaltr/shikari"
author = "cmdaltr"

[tool.briefcase.app.shikari]
formal_name = "Shikari"
description = "Threat hunting and detection engineering"
long_description = """Shikari generates SIEM detections (Google SecOps, Microsoft Defender, Splunk, Elastic) from MITRE ATT&CK techniques, threat groups, CVEs and threat reports. Run it on this computer or connect to your organisation's Shikari server."""
icon = "icons/shikari"
sources = {toml_list(["shikari", "templates", "static", "seed", *extra_sources])}
requirement_installer_args = ["--find-links", "{wheels.as_posix()}"]

[tool.briefcase.app.shikari.macOS]
# One build per architecture (CI builds both): not every dependency has universal2 wheels
universal_build = false
requires = {toml_list(webview, "        ")}

[tool.briefcase.app.shikari.windows]
requires = {toml_list(webview, "        ")}

[tool.briefcase.app.shikari.linux]
# Read by desktop/build_deb.py, not Briefcase: the .deb bundles its own Python and uses the distro's
# GTK and WebKit (Qt would add several hundred MB)
requires = {toml_list([w.replace("pywebview", "pywebview[gtk]") for w in webview], "        ")}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    # Outside the repository by default: a build is hundreds of MB, and the checkout may be in a synced folder
    parser.add_argument("--out", type=Path, default=Path.home() / ".cache" / "shikari" / "desktop")
    parser.add_argument("--attack", type=Path, help="enterprise-attack.json to bundle (and its .meta.json if beside it)")
    parser.add_argument("--procedures", type=Path, nargs="*", default=[],
                        help="mitre_procedures.csv (and .meta.json / .xlsx) to bundle")
    parser.add_argument("--mingit", choices=sorted(MINGIT), help="bundle MinGit for this Windows architecture "
                        "(the default on Windows is the machine's own; elsewhere, none)")
    args = parser.parse_args()

    out = args.out.resolve()
    if out.exists():
        # Only ever the staging folder: refuse anything that isn't one
        if not (out / "pyproject.toml").exists() or "Generated by desktop/stage.py" not in (out / "pyproject.toml").read_text():
            sys.exit(f"{out} exists and isn't a staged tree; remove it or pick another --out")
        shutil.rmtree(out)
    out.mkdir(parents=True)

    files = git_files()
    staged = seeded = 0
    for rel in files:
        src = ROOT / rel
        if not src.is_file():
            continue  # deleted in the working tree
        top = rel.parts[0]
        if top in CODE:
            dest = out / rel
        elif top == "data":
            dest = out / "seed" / rel
            seeded += 1
        else:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
        staged += 1

    if args.attack:
        cache = out / "seed" / "shikari" / "data" / "cache"
        cache.mkdir(parents=True, exist_ok=True)
        for f in (args.attack, args.attack.with_name(args.attack.name + ".meta.json")):
            if f.exists():
                shutil.copy2(f, cache / f.name)
                seeded += 1
    for f in args.procedures:
        # After the bundle, so the CSV is the newer of the two (shikari.app rebuilds it otherwise)
        shutil.copy2(f, out / "seed" / "data" / f.name)
        (out / "seed" / "data" / f.name).touch()
        seeded += 1

    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    (out / "seed" / "VERSION").write_text(project["version"] + "\n")
    shutil.copytree(ROOT / "desktop" / "icons", out / "icons")
    shutil.copy2(ROOT / "LICENSE", out / "LICENSE")
    # Inside seed/ too, which the app carries: Help > Licence shows it (LICENSE itself isn't a source)
    shutil.copy2(ROOT / "LICENSE", out / "seed" / "LICENSE")
    # And the install scripts: the app updates itself with them (shikari/updates.py). The uninstall
    # scripts ride along, so an installed copy can remove itself without the repository
    for script in ("install.sh", "install.ps1", "uninstall.sh", "uninstall.ps1"):
        shutil.copy2(ROOT / "desktop" / script, out / "seed" / script)
    # Debian packages must carry one; the release notes live on GitHub
    (out / "CHANGELOG.md").write_text(f"# {project['version']}\n\nSee https://github.com/cmdaltr/shikari/releases\n")
    wheels = out / "wheels"
    pinned = {requirement_name(d): d for d in project["dependencies"]}
    for name in sorted(SDIST_ONLY):
        subprocess.run([sys.executable, "-m", "pip", "wheel", "-q", "--no-deps", "-w", str(wheels), pinned.get(name, name)],
                       check=True)
    if sys.platform == "win32" and platform.machine().upper() == "ARM64":
        # Several pins publish no Windows ARM64 wheel (aiohttp, pandas, PyYAML, bcrypt, evtx...), and the
        # releases that do are major upgrades, so those are compiled here (MSVC, and Rust for bcrypt and
        # evtx); the rest are downloaded as they are
        bundled = [NO_SDIST.get(requirement_name(d), "").format(version=d.split("==")[-1]) or d
                   for d in project["dependencies"] if requirement_name(d) not in NOT_BUNDLED]
        subprocess.run([sys.executable, "-m", "pip", "wheel", "-q", "--no-deps", "-w", str(wheels), *bundled], check=True)
    machine = args.mingit or (platform.machine().upper() if sys.platform == "win32" else None)
    extra = []
    if machine:
        print(f"Bundled {stage_mingit(out, machine)}")
        extra.append("mingit")
    (out / "pyproject.toml").write_text(pyproject(project, wheels, extra))
    # Packages install as root for every user, and a synced or private checkout can hold 0700 files
    for p in out.rglob("*"):
        p.chmod(0o755 if p.is_dir() else 0o644)
    print(f"Staged {staged} files ({seeded} seed) in {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
